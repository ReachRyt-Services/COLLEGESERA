<p>TNEA (Tamil Nadu Engineering Admissions) is the state’s centralised admission process for BE/BTech seats in Tamil Nadu. Unlike many other states, Tamil Nadu does not conduct an entrance exam for engineering. Instead, admission is based on Class 12 marks, specifically in:</p>
<ul>
    <li>Mathematics</li>
