<h3>STEP 3: TNEA Certificate Verification (Online)</h3>
<p>Now, the entire verification usually happens online. Your documents are reviewed, and if there is any problem, you’ll be asked to re-upload.</p>
<p><strong>Things Students Often Miss:</strong> Not checking the portal regularly, missing resubmission deadlines, or uploading temporary certificates instead of valid ones.</p>

<h3>STEP 4: How TNEA Calculates Your Score (Out of 200)</h3>
<p>TNEA converts your Class 12 marks to a weighted score:</p>
<ul>
    <li>Mathematics → scaled to 100</li>
    <li>Physics → scaled to 50</li>
    <li>Chemistry → scaled to 50</li>
    <li><strong>Total = 200</strong></li>
</ul>
<p><em>Example:</em> If you scored Maths: 90, Physics: 85, Chemistry: 80</p>
<p>Converted score: 90 (Maths) + 42.5 (Physics / 2) + 40 (Chemistry / 2) = <strong>172.5 / 200</strong>. This score determines your rank.</p>

