<p><strong>Tie-Breaking Sequence:</strong></p>
<ol>
    <li>Higher Maths marks</li>
    <li>Higher Physics marks</li>
    <li>Higher Chemistry marks</li>
    <li>Higher marks in 4th subject</li>
    <li>Elder candidate gets preference</li>
</ol>

<h3>STEP 6: TNEA Counselling Call Letter</h3>
