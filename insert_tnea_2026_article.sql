<h3>STEP 1: Registration for TNEA (Online Application)</h3>
<p>TNEA registration usually opens around May-June, after Class 12 results.</p>
<p>During registration, you provide basic details like:</p>
<ul>
    <li>Name, Date of birth, Email and mobile number</li>
    <li>Class 12 board and marks info</li>
    <li>Community category</li>
